// 가상 브랜드 샘플 하단 고지 — **문구는 여기 한 곳이 정본이다.**
//
// 2026-09-18 형 지시: 데모마다 문구가 10가지 넘게 제각각이었다(「실제 업체가 아닙니다」 · 「실제 업체가 아니며
// 화면의 회사명·…」 · 「주문·결제는 접수되지 않습니다」 …). 한 문장으로 통일하고 규칙으로 박는다.
//
// 문구에서 지킨 것
// - 「가상」은 빼지 않는다. 「태문넷의 브랜드 샘플」이면 「태문이 이 브랜드를 위해 만든 샘플」로 읽혀
//   화면 속 회사가 실존하는 것처럼 보인다. 「가상」 두 글자가 「이 회사는 없다」를 말해 준다.
// - 저작권은 「© 연도 상호」 관례 표기로. 디자인이 생성형 AI 로 나왔고(보호 범위가 사람이 고르고 고친 부분으로
//   좁혀질 수 있다) 사진 일부는 언스플래시 것이라, 「저작권은 ○○에 있습니다」 같은 문장형 선언은 실제보다 세다.
// - 상호는 사업자등록증 그대로 「주식회사 태문」.
// - 「접수되지 않습니다」는 여기 넣지 않는다 — 폼마다 제출 버튼 위에 따로 붙고 검사가 그걸 강제한다.
//
// 쓰는 법: 각 데모 푸터의 고지 자리에 <SampleFooterNote /> 를 넣는다. **<span> 을 그리므로** <p>·<span> 안에
// 넣어도 된다(<p> 안에 <p> 를 넣으면 수화 오류가 난다). 색·크기는 감싼 요소를 따른다 — 데모마다 디자인이 달라서다.
//
// ⚠️ 제안용 시안(kind=proposal — 실존 업체)에는 쓰지 않는다. 그 회사는 「가상」이 아니다.
//    거기는 (demos) 레이아웃의 DemoDisclaimer 가 「해당 회사가 만들었거나 의뢰한 사이트가 아닙니다」를 붙인다.

export const SAMPLE_FOOTER_TEXT = "이 화면은 태문넷의 가상 브랜드 샘플입니다. © 2026 주식회사 태문";

export function SampleFooterNote({ className }: { className?: string }) {
  return (
    <span className={className} data-sample-footer-note="">
      {SAMPLE_FOOTER_TEXT}
    </span>
  );
}

export default SampleFooterNote;
